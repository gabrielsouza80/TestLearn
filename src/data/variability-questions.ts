import type { Question } from '../domain/engine';
type Pair = [en: string, pt: string];
type Option = [en: string, pt: string, reasonEn: string, reasonPt: string];
const text = ([en, pt]: Pair) => ({ en, pt });
function original(
  n: number,
  lo: string,
  level: Question['level'],
  topic: string,
  section: string,
  pages: number[],
  prompt: Pair,
  options: Option[],
  correct: string,
  explanation: Pair,
  table?: Question['table'],
): Question {
  return {
    id: `tl-${String(n).padStart(3, '0')}`,
    chapter: Number(lo[3]),
    lo,
    level,
    topic,
    type: table ? 'table' : level === 'K3' ? 'scenario' : 'single',
    required: 1,
    text: text(prompt),
    options: options.map(([en, pt, reasonEn, reasonPt], i) => ({
      id: `o${i + 1}`,
      text: { en, pt },
      explanation: { en: reasonEn, pt: reasonPt },
    })),
    correct: [correct],
    explanation: text(explanation),
    ...(table ? { table } : {}),
    origin: 'original',
    syllabus: '4.0.1',
    version: 1,
    review: 'AI_REVIEWED',
    translationReview: 'AI_REVIEWED',
    humanApproval: 'PENDING',
    examEligible: true,
    tags: ['phase5a-variability'],
    academicReview: {
      method: 'AI_REVIEWED',
      status: 'PASS',
      reviewedAt: '2026-10-28',
      section,
      pages,
      report: `docs/academic-audit.md#fase-5a--tl-${String(n).padStart(3, '0')}`,
    },
  };
}
