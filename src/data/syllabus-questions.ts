import type { Question } from '../domain/engine';

type Pair = [en: string, pt: string];
type Alternative = [en: string, pt: string, reasonEn: string, reasonPt: string];
const bilingual = ([en, pt]: Pair) => ({ en, pt });
// Option IDs belong to the authored order; display shuffling never changes them.
function question(
  id: string,
  lo: string,
  level: Question['level'],
  topic: string,
  pages: number[],
  prompt: Pair,
  alternatives: Alternative[],
  correct: string,
  explanation: Pair,
): Question {
  return {
    id,
    lo,
    chapter: Number(lo[3]),
    level,
    topic,
    type: 'single',
    required: 1,
    text: bilingual(prompt),
    options: alternatives.map(([en, pt, reasonEn, reasonPt], index) => ({
      id: `o${index + 1}`,
      text: { en, pt },
      explanation: { en: reasonEn, pt: reasonPt },
    })),
    correct: [correct],
    explanation: bilingual(explanation),
    origin: 'original',
    syllabus: '4.0.1',
    version: 1,
    review: 'AI_REVIEWED',
    translationReview: 'AI_REVIEWED',
    humanApproval: 'PENDING',
    examEligible: true,
    tags: ['syllabus-coverage-phase4'],
    academicReview: {
      method: 'AI_REVIEWED',
      status: 'PASS',
      reviewedAt: '2026-10-27',
      section: lo.slice(3),
      pages,
      report: `docs/academic-audit.md#${id}`,
    },
  };
}

